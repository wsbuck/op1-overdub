#!/usr/bin/env python3
"""Generate src/slot/wah_table.h: the wah treadle's face matrices (pedals.svg ttop, tside, tend) over the rock
amount a = -1 (heel down) .. +1 (toe down), from the 3D model in gen_rot.py. ui.c interpolates linearly.
  python3 design/fx/gen_wah_table.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_rot as g  # noqa: E402

STEPS = 16
FACES = ("ttop", "tside", "tend")


def main():
    rows = []
    for i in range(STEPS + 1):
        a = -1 + 2 * i / STEPS
        m = g.treadle_a(a)
        rows.append([round(v * 1024) for f in FACES for v in m[f]])
    out = os.path.join(HERE, "..", "..", "src", "slot", "wah_table.h")
    with open(out, "w") as f:
        f.write("/* Generated by design/fx/gen_wah_table.py: pedals.svg treadle face matrices {a, b, c, d, e, f} (Q10)\n"
                f" * for ttop, tside, tend at rock a = -1 + 2 i / {STEPS} (heel down .. toe down). */\n")
        f.write(f"#define WAH_STEPS {STEPS}\n")
        f.write(f"static const int32_t wah_table[WAH_STEPS + 1][18] = {{\n")
        for r in rows:
            f.write("    { " + ", ".join(map(str, r)) + " },\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
