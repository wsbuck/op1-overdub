#!/usr/bin/env python3
"""Write design/synth/fm4.svg: the fm4 engine screen's gear train (src/slot/ui_fm4.h), TE renderer subset
(notes/svg-route.md; check with design/fx/check_svg.py). Our own artwork.  Usage: gen_fm4.py [OUT.svg]

Every gear has the same tooth pitch (PITCH units), so any two mesh: a size is a tooth count (SIZES), and each operator
group holds one variant per size; the code shows the one its ratio picks. Style (after TE's own display art: tape
reels, crank LFO, clock): 1.5-unit outlines, chunky teeth with rounded tips, a black-filled body so overlaps stay
clean, a thin dark-blue inner ring, three spokes with rounded ends, a ringed hub. The code recolours the outline and
the hub: carriers grey .. white with their level (white = the gear you hear), modulators dark blue .. blue with their
bite, the selected operator white with its ring shown.
"""
import math
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fx"))
import strictify

PITCH = 6.0                                 # tooth pitch at the pitch radius, units
SIZES = (9, 14, 21)                         # tooth counts (= fu_teeth in ui_fm4.h)
DEPTH = 3.4                                 # tooth depth (= 2 x FU_HDEPTH in ui_fm4.h)
OPS = "abcd"

# runtime-recoloured strokes: one unique value (+-1 of a colors.svg colour) per operator and role, shared by that
# operator's size variants (the code gives them all the same colour, so even a shared style entry is harmless)
_used, _per = set(), {}


def per(key, base):
    if key in _per:
        return _per[key]
    r, g, b = int(base[1:3], 16), int(base[3:5], 16), int(base[5:7], 16)
    for dr in (0, -1, 1):
        for dg in (0, -1, 1):
            for db in (0, -1, 1):
                c = f"#{min(255, max(0, r + dr)):02X}{min(255, max(0, g + dg)):02X}{min(255, max(0, b + db)):02X}"
                if c not in _used:
                    _used.add(c)
                    _per[key] = c
                    return c
    raise SystemExit("out of unique colours for " + base)


def f(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def pol(r, deg):
    a = math.radians(deg)
    return r * math.cos(a), r * math.sin(a)


def xy(p):
    return f"{f(p[0])} {f(p[1])}"


def body_path(n):
    """Chunky teeth (tooth 0 centred at angle 0, as the code's phase maths assumes): straight flanks from the root
    circle, a rounded tip (one cubic), straight root lands between teeth."""
    rp = n * PITCH / (2 * math.pi)
    ro, ri = rp + DEPTH / 2, rp - DEPTH / 2
    step = 360 / n
    d = []
    for i in range(n):
        c = i * step
        a0, a1 = c - 0.28 * step, c - 0.14 * step            # flank: root -> shoulder
        b1, b0 = c + 0.14 * step, c + 0.28 * step
        p0, p1, q1, q0 = pol(ri, a0), pol(ro - 0.5, a1), pol(ro - 0.5, b1), pol(ri, b0)
        k1, k2 = pol(ro + 0.35, c - 0.09 * step), pol(ro + 0.35, c + 0.09 * step)     # round tip
        d.append(("M" if i == 0 else "L") + xy(p0))
        d.append("L" + xy(p1))
        d.append("C" + xy(k1) + " " + xy(k2) + " " + xy(q1))
        d.append("L" + xy(q0))
    return " ".join(d) + " Z", rp, ro, ri


def variant(op, j, n):
    d, rp, ro, ri = body_path(n)
    ring = ri - 2.2
    hub = max(2.8, rp * 0.26)
    spokes = " ".join(f"M{xy(pol(hub + 1.2, a))} L{xy(pol(ring - 1.2, a))}" for a in (-90, 30, 150))
    vid = f"g{op}{j}"
    return (f'    <g id="{vid}">\n'
            f'      <path id="{vid}body" d="{d}" fill="#010000" stroke="{per(op + "body", "#E6E7FF")}" stroke-width="1.5" stroke-linejoin="round"/>\n'
            f'      <circle cx="0" cy="0" r="{f(ring)}" fill="none" stroke="#383572" stroke-width="1"/>\n'
            f'      <path d="{spokes}" fill="none" stroke="#7C7990" stroke-width="2" stroke-linecap="round"/>\n'
            f'      <circle id="{vid}hub" cx="0" cy="0" r="{f(hub)}" fill="#010000" stroke="{per(op + "hub", "#E6E7FF")}" stroke-width="1.5"/>\n'
            f'      <circle cx="0" cy="0" r="1.2" fill="#AEB1DC"/>\n'
            f'      <circle id="{vid}sel" cx="0" cy="0" r="{f(ro + 2.6)}" fill="none" stroke="#FFFFFF" stroke-width="1"/>\n'
            f'    </g>\n')


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "fm4.svg")
    tip = (14.1, -14.1)
    gears = "".join(f'  <g id="g{op}">\n' + "".join(variant(op, j, n) for j, n in enumerate(SIZES)) + "  </g>\n"
                    for op in "dcba")
    svg = f'''<?xml version="1.0" encoding="utf-8"?>
<!--
fm4.svg - the fm4 synth engine screen (Operator-style FM, notes/harm-fm4.md): every operator is a gear, the algorithm
is the gear train. Our own artwork, generated by design/synth/gen_fm4.py. TE's retained renderer draws it, then
src/slot/ui_fm4.h draws the text on top with our stroke font. Ids are found once (find, assert=0); the code places
everything (gears drawn at their axle).
  belt1, belt2      a modulator's further targets: (0,0)-(100,0) mapped onto the centre-to-centre segment
  gX                operator X: matrix = translate(axle) * rotate(angle) * the train's scale; one variant gXj per size
                    (tooth counts {", ".join(map(str, SIZES))}, pitch {f(PITCH)}), the others hidden
  gXjbody, gXjhub   stroke recoloured: carriers grey .. white by level, modulators dark blue .. blue by bite [blue],
                    the selected page white
  gXjsel            shown only on that operator's page
  pawl              feedback on D: shown when feedback > 0, scaled with D's size and feedback, chattering [orange];
                    arm, pivot, spring recoloured
-->
<svg version="1.1" xmlns="http://www.w3.org/2000/svg" x="0" y="0" width="320" height="160" viewBox="0 0 320 160">
  <line id="belt1" x1="0" y1="0" x2="100" y2="0" stroke="{per("belt1", "#698EFF")}" stroke-width="2" stroke-linecap="round"/>
  <line id="belt2" x1="0" y1="0" x2="100" y2="0" stroke="{per("belt2", "#698EFF")}" stroke-width="2" stroke-linecap="round"/>
{gears}  <g id="pawl">
    <path id="spring" d="M23.5 -27.5 L29.5 -30 L24.5 -33 L30.5 -35.5 L25.5 -38.5 L31 -41" fill="none" stroke="{per("spring", "#FF423F")}" stroke-width="1.3" stroke-linejoin="round" stroke-linecap="round"/>
    <line x1="25" y1="-42.5" x2="35" y2="-42.5" stroke="#7C7990" stroke-width="2" stroke-linecap="round"/>
    <path id="arm" d="M24 -26 L{f(tip[0] + 0.6)} {f(tip[1] - 0.6)} L{f(tip[0] + 3.2)} {f(tip[1] + 0.4)} Z" fill="#010000" stroke="{per("arm", "#FF423F")}" stroke-width="1.5" stroke-linejoin="round"/>
    <circle id="pivot" cx="24" cy="-26" r="2.2" fill="#010000" stroke="{per("pivot", "#FF423F")}" stroke-width="1.3"/>
  </g>
</svg>
'''
    open(out, "w").write(svg)
    strictify.strictify_file(out)                                   # one subpath per element (TE joins subpaths)


if __name__ == "__main__":
    main()
