#!/usr/bin/env python3
"""Write design/synth/fm4.svg: the fm4 engine screen's gear train (src/slot/ui_fm4.h), TE renderer subset
(notes/svg-route.md; check with design/fx/check_svg.py). Our own artwork.  Usage: gen_fm4.py [OUT.svg]"""
import math
import os
import sys

R_TIP, R_ROOT, TEETH = 20.0, 16.4, 12
# per gear: recoloured strokes, unique per element (+-1 of a colors.svg value: TE keeps one style per element anyway)
BODY = {"a": "#E6E7FF", "b": "#E6E7FE", "c": "#E6E6FF", "d": "#E7E7FF"}
HUB = {"a": "#E5E7FF", "b": "#E6E8FF", "c": "#E7E6FF", "d": "#E5E6FF"}


def f(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def pol(r, deg):
    a = math.radians(deg)
    return r * math.cos(a), r * math.sin(a)


def gear(n):
    pts = []
    step = 360 / TEETH
    for i in range(TEETH):
        c = i * step
        for r, d in ((R_ROOT, c - 9.5), (R_TIP, c - 4.5), (R_TIP, c + 4.5), (R_ROOT, c + 9.5)):
            pts.append(pol(r, d))
    poly = " ".join(f"{f(x)},{f(y)}" for x, y in pts).replace(",", " ")
    spokes = " ".join(f"M{f(pol(5.6, a)[0])} {f(pol(5.6, a)[1])} L{f(pol(12, a)[0])} {f(pol(12, a)[1])}"
                      for a in (-90, 30, 150))
    return f'''  <g id="g{n}">
    <circle id="g{n}sel" cx="0" cy="0" r="23.2" fill="none" stroke="#FFFFFF" stroke-width="1"/>
    <polygon id="g{n}body" points="{poly}" fill="#010000" stroke="{BODY[n]}" stroke-width="1.3" stroke-linejoin="round"/>
    <circle id="g{n}rim" cx="0" cy="0" r="12.6" fill="none" stroke="#383572" stroke-width="0.9"/>
    <path id="g{n}spokes" d="{spokes}" fill="none" stroke="#7C7990" stroke-width="1.4" stroke-linecap="round"/>
    <circle id="g{n}hub" cx="0" cy="0" r="5" fill="#010000" stroke="{HUB[n]}" stroke-width="1.3"/>
    <circle id="g{n}axle" cx="0" cy="0" r="1.6" fill="#7C7990"/>
  </g>'''


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "fm4.svg")
    tip = pol(R_TIP, -45)
    pawl = f'''  <g id="pawl">
    <path id="spring" d="M23.5 -27.5 L29.5 -30 L24.5 -33 L30.5 -35.5 L25.5 -38.5 L31 -41" fill="none" stroke="#FF423E" stroke-width="1.2" stroke-linejoin="round" stroke-linecap="round"/>
    <line id="anchor" x1="25" y1="-42.5" x2="35" y2="-42.5" stroke="#7C7990" stroke-width="1.5" stroke-linecap="round"/>
    <path id="arm" d="M24 -26 L{f(tip[0] + 0.6)} {f(tip[1] - 0.6)} L{f(tip[0] + 3.2)} {f(tip[1] + 0.4)} Z" fill="#010000" stroke="#FF423F" stroke-width="1.5" stroke-linejoin="round"/>
    <circle id="pivot" cx="24" cy="-26" r="2.2" fill="#010000" stroke="#FF433F" stroke-width="1.2"/>
  </g>'''
    svg = f'''<?xml version="1.0" encoding="utf-8"?>
<!--
fm4.svg - the fm4 synth engine screen (Operator-style FM, notes/harm-fm4.md): every operator is a gear, the algorithm
is the gear train. Our own artwork, generated by design/synth/gen_fm4.py. TE's retained renderer draws it, then
src/slot/ui_fm4.h draws the text (labels, readouts) on top with our stroke font. All ids are found once at load
(find, assert=0). Every gear is drawn at the origin with tip radius {f(R_TIP)}; the code places it.
  belt1, belt2      a modulator's further targets: matrix maps (0,0)-(100,0) onto the centre-to-centre segment
                    (unit-length normal, so the width stays); recolour stroke by tooth bite (darkblue/lightblue/blue)
  gA..gD            matrix = translate(centre) * rotate(angle + jitter) * scale(radius / {f(R_TIP)}); centre and radius from
                    the algorithm layout fitted to the screen, angle from the envelope-driven spin [green: algorithm]
  gXbody, gXhub     recolour stroke: carriers by level (grey .. white), modulators by tooth bite (darkblue .. blue)
                    [blue: index], the selected operator page white
  gXsel             shown only on that operator's page
  pawl              shown when feedback > 0; matrix = gear D's translate * scale, then scale(0.7 .. 1.2) about the
                    tooth contact, then a chatter rotation about the pivot while a note sounds [orange: feedback]
  arm, pivot, spring  recolour stroke: offred (feedback < 1/8) or orange
  everything else   static per gear (rim, spokes, axle).
-->
<svg version="1.1" xmlns="http://www.w3.org/2000/svg" x="0" y="0" width="320" height="160" viewBox="0 0 320 160">
  <line id="belt1" x1="0" y1="0" x2="100" y2="0" stroke="#698EFF" stroke-width="2" stroke-linecap="round"/>
  <line id="belt2" x1="0" y1="0" x2="100" y2="0" stroke="#698EFE" stroke-width="2" stroke-linecap="round"/>
{gear("d")}
{gear("c")}
{gear("b")}
{gear("a")}
{pawl}
</svg>
'''
    open(out, "w").write(svg)


if __name__ == "__main__":
    main()
