#!/usr/bin/env python3
"""Generate va_tables.h: the cutoff -> ZDF SVF g table for va.c.

  python3 src/engine/gen_va_tables.py > src/engine/va_tables.h

g = tan(pi * fc / fs) in Q28, at CUTOFF_POINTS knob positions spaced exponentially from F_LO to F_HI.
va.c interpolates linearly between points. F_HI keeps g small enough that the filter's
1 + g(g + k) stays below 2^31 in Q28 (see va.c).
"""
import math

FS = 44100.0
F_LO, F_HI = 20.0, 14000.0
CUTOFF_POINTS = 65
Q28 = 1 << 28

rows = []
for i in range(CUTOFF_POINTS):
    fc = F_LO * (F_HI / F_LO) ** (i / (CUTOFF_POINTS - 1))
    rows.append(round(math.tan(math.pi * fc / FS) * Q28))

print("/* Generated by gen_va_tables.py; do not edit. */")
print(f"/* g = tan(pi fc / {FS:g}) in Q28, fc = {F_LO:g} Hz .. {F_HI:g} Hz exponential, {CUTOFF_POINTS} points. */")
print(f"#define VA_CUTOFF_POINTS {CUTOFF_POINTS}")
print("static const int32_t va_cutoff_g[VA_CUTOFF_POINTS] = {")
for i in range(0, len(rows), 6):
    print("    " + " ".join(f"{v}," for v in rows[i:i + 6]))
print("};")
