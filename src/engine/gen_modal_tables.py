#!/usr/bin/env python3
"""Generate modal_tables.h for modal.c (fixed-point port of krystal's Modal engine).

  python3 src/engine/gen_modal_tables.py > src/engine/modal_tables.h

Tables:
  modal_log2r[8][MODES]  log2 of each material's mode ratio, Q16 (krystal materialRatio, jitter seed 7)
  modal_weight[MODES]    strike-position weight (position 0.30) * 35 / sqrt(n), Q24
  sin_q30[1025]          sin(2 pi i / 1024), Q30 (1025th entry for interpolation)
  exp2neg_q31[257]       2^(-i / 256), Q31 (first entry saturated to 0x7FFFFFFF)
"""
import math

MODES = 20
POSITION = 0.30


def lcg_uniform(seed, n):
    """krystal dsp::Lcg(seed).uniform(): s = s * 1664525 + 1013904223, uniform = s / 2^32."""
    s = seed & 0xFFFFFFFF
    out = []
    for _ in range(n):
        s = (s * 1664525 + 1013904223) & 0xFFFFFFFF
        out.append(s / 4294967296.0)
    return out


JIT = [u - 0.5 for u in lcg_uniform(7, 64 + 2)]


def material_ratio(m, n):
    if m == 0:
        return float(n)
    if m == 1:
        b = (2.0 * n + 1.0) / 3.0
        return b * b
    if m == 2:
        return n ** 1.35 * (1.0 if n & 1 else 0.93)
    if m == 3:
        return 1.0 + 0.42 * (n - 1) ** 0.92 * (1.0 + 0.06 * JIT[n])
    if m == 4:
        return math.sqrt(n * (n + 1.0) / 2.0)
    if m == 5:
        return n ** 1.2 * (1.0 + 0.015 * n)
    if m == 6:
        return ((n + 1) >> 1) * (1.0 if n & 1 else 1.012)
    return n + 0.5 * math.sin(n * 2.399)


def rows(vals, per=8):
    return "\n".join("    " + " ".join(f"{v}," for v in vals[i:i + per]) for i in range(0, len(vals), per))


def main():
    print("/* Generated by gen_modal_tables.py; do not edit. */")
    print("#ifndef MODAL_TABLES_H\n#define MODAL_TABLES_H\n#include <stdint.h>\n")
    print(f"#define MODES {MODES}")
    print("static const int32_t modal_log2r[8][MODES] = {")
    for m in range(8):
        print("  {" + " ".join(f"{round(math.log2(material_ratio(m, n)) * 65536)}," for n in range(1, MODES + 1)) + "},")
    print("};")
    w = []
    for n in range(1, MODES + 1):
        sw = 0.04 + 0.96 * abs(math.sin(math.pi * (0.08 + 0.42 * POSITION) * n)) ** 2.5
        w.append(round(sw * 35 / math.sqrt(n) * (1 << 24)))
    print("static const int32_t modal_weight[MODES] = {\n" + rows(w) + "\n};")
    print("static const int32_t sin_q30[1025] = {\n" + rows([round(math.sin(2 * math.pi * i / 1024) * (1 << 30)) for i in range(1025)]) + "\n};")
    e = [min(0x7FFFFFFF, round(2 ** (-i / 256) * (1 << 31))) for i in range(257)]
    print("static const int32_t exp2neg_q31[257] = {\n" + rows(e) + "\n};")
    print("\n#endif")


if __name__ == "__main__":
    main()
