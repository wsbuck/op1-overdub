#!/usr/bin/env python3
"""Generate the space (reverb) FX tables, src/slot/space_tables.h.

  python3 src/slot/gen_space.py

The output is committed; rerun after changing a space in design/fx/reverb_proto/proto.py (the anchors and early
reflections live there once: SPACES, ER, BASE_MS, AP_MS, ER_AP_MS, ER_R_SKEW). FX: src/slot/space.c; design:
notes/fx-reverb.md.

Tables:
  sp_pt[33]   the space morph at every detent of blue (raw d * 1024, the last at 32767), from proto.py space_at():
              geometric between anchors for times, sizes and frequencies, linear otherwise; space.c interpolates
              linearly between detents (inside a detent the geometric and the linear morph differ by < 0.5 %)
  sp_coef     one-pole coefficient a = 1 - exp(-2 pi f / fs), Q15, per tank rate, on log2 f in 1/16 octaves
  sp_exp2     2^(-j / 256), Q30: line gains 2^-e
  sp_win      sin(pi i / 1024), Q15: the shimmer heads' windows
  sp_shbq     the shimmer's anti-alias low-pass (RBJ biquad, Q 0.7071) per tank rate, for +12, for +12+19 and for
              SUB -12 (2 kHz: the octave down kept clean; run once), Q14 (the 22.05 kHz tank runs the shimmer's twice:
              4th order, its alias band is an octave lower)
  sp_hb       the half-band filter (31 taps, Kaiser) for the 22.05 kHz tank: the 8 odd taps, Q15
"""
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "design", "fx", "reverb_proto"))
import proto  # noqa: E402

OUT = os.path.join(HERE, "space_tables.h")
COEF_LO, COEF_STEPS = 4, 169            # log2 f from 4 (16 Hz) in 1/16 octaves: 16 Hz .. 23 kHz
HB_TAPS = 31


def hb_taps():
    """Half-band low-pass, cut-off fs / 4: windowed sinc, Kaiser beta 6. Even taps (but the centre) are 0."""
    n = np.arange(HB_TAPS) - (HB_TAPS - 1) // 2
    h = np.sinc(n / 2) / 2 * np.kaiser(HB_TAPS, 6.0)
    h /= h.sum()
    return h


def main():
    rows = []
    for d in range(33):
        k = 32767 if d == 32 else d * 1024
        s = proto.space_at(k)
        sz = s["size"]
        ersc = min(sz, 1.6) ** 0.5
        row = [round(sz * 65536), round(math.sqrt(sz) * 65536), round(s["t60"] * 1000),
               round(math.log2(s["t60"]) * 65536), round(s["hi"] * 32768), round(math.log2(s["xover"]) * 65536),
               round(s["pre"] * 256), round(s["erlev"] * 32768), round(s["diff"] * 32768), round(s["mdep"] * 256),
               round(s["mrate"] * 65536), round(math.log2(s["hp"]) * 65536), round(math.log2(s["lp"]) * 65536)]
        row += [round(ms * ersc * 256) for ms in s["er_t"]]
        row += [round(g * 0.35 * 32768) for g in s["er_g"]]
        rows.append(row)
    names = ["size", "sqrts", "t60_ms", "l2t60", "hi", "lxo", "pre", "erlev", "diff", "mdep", "mrate", "lhp", "llp"]
    nf = len(names) + 16

    coef = {}
    for fs in (44100, 22050):
        coef[fs] = [min(32767, round((1 - math.exp(-2 * math.pi * 2 ** (COEF_LO + i / 16) / fs)) * 32768))
                    for i in range(COEF_STEPS)]
    h = hb_taps()
    mid = (HB_TAPS - 1) // 2
    hb = [round(h[mid + 1 + 2 * j] * 32768) for j in range(8)]      # taps +-1, +-3, .. +-15 (symmetric)
    hb[0] -= (2 * sum(hb) + 16384 - 32768) // 2                    # unity at DC exactly

    L = []
    w = L.append
    w("/* Generated by src/slot/gen_space.py from design/fx/reverb_proto/proto.py; do not edit.")
    w(" * The space (reverb) FX's tables: the morph of blue per detent, filter coefficients, gains, windows. */")
    w("#ifndef SPACE_TABLES_H\n#define SPACE_TABLES_H\n#include <stdint.h>\n")
    w("/* sp_pt[d][field] at blue = d * 1024 (d 32: 32767). Q16 = x 65536, Q15 = x 32768, Q8 = x 256; l2 = log2.")
    w(" * ER: the 8 tap times (ms after the predelay, Q8, already x sqrt(min(size, 1.6))), then their gains (Q15,")
    w(" * x 0.35). R's taps are L's x SP_ER_R_SKEW (Q14). */")
    for i, nm in enumerate(names):
        w(f"#define SP_{nm.upper()} {i}")
    w(f"#define SP_ERT {len(names)}\n#define SP_ERG {len(names) + 8}\n#define SP_NF {nf}")
    w(f"static const int32_t sp_pt[33][SP_NF] = {{")
    for r in rows:
        w("    { " + ", ".join(map(str, r)) + " },")
    w("};\n")
    w("/* FDN line lengths at size 1 (proto.py BASE_MS), input allpasses L1..L4 R1..R4 (AP_MS) and the ER allpasses")
    w(" * L1 L2 R1 R2 (ER_AP_MS), in samples at 44.1 kHz, Q4 */")
    w("static const int32_t sp_base[8] = { " + ", ".join(str(round(ms * 44.1 * 16)) for ms in proto.BASE_MS) + " };")
    w("static const int32_t sp_ap_base[8] = { " + ", ".join(str(round(ms * 44.1 * 16)) for ms in proto.AP_MS) + " };")
    w("static const int32_t sp_erap_base[4] = { " + ", ".join(str(round(ms * 44.1 * 16)) for ms in proto.ER_AP_MS)
      + " };")
    w("static const int32_t sp_er_r_skew[8] = { " + ", ".join(str(round(v * 16384)) for v in proto.ER_R_SKEW) + " };\n")
    w(f"/* one-pole a = 1 - exp(-2 pi f / fs), Q15, at log2 f = {COEF_LO} + i / 16: [0] 44.1 kHz, [1] 22.05 kHz */")
    w(f"#define SP_COEF_LO {COEF_LO}\n#define SP_COEF_N {COEF_STEPS}")
    w("static const int16_t sp_coef[2][SP_COEF_N] = {")
    for fs in (44100, 22050):
        vals = coef[fs]
        w("    {")
        for i in range(0, len(vals), 16):
            w("        " + ", ".join(map(str, vals[i:i + 16])) + ",")
        w("    },")
    w("};\n")
    w("/* 2^(-j / 256), Q30, j = 0 .. 256 */")
    e = [round(2 ** (-j / 256) * (1 << 30)) for j in range(257)]
    w("static const int32_t sp_exp2[257] = {")
    for i in range(0, 257, 8):
        w("    " + ", ".join(map(str, e[i:i + 8])) + ",")
    w("};\n")
    w("/* sin(pi i / 1024), Q15 (i = 1024: 0) */")
    win = [min(32767, round(math.sin(math.pi * i / 1024) * 32768)) for i in range(1025)]
    w("static const int16_t sp_win[1025] = {")
    for i in range(0, 1025, 16):
        w("    " + ", ".join(map(str, win[i:i + 16])) + ",")
    w("};\n")
    w(f"/* half-band low-pass ({HB_TAPS} taps, cut-off fs / 4, Kaiser 6): centre 0.5, taps +-1, +-3 .. +-15, Q15 */")
    w("static const int16_t sp_hb[8] __attribute__((aligned(4))) = { " + ", ".join(map(str, hb)) + " };\n")
    w("/* shimmer anti-alias low-pass, RBJ biquad Q 0.7071, {b0, b1, b2, a1, a2} Q14 (b0 + b1 + b2 = 1 + a1 + a2):")
    w(" * [rate: 44.1 / 22.05 kHz][+12 / +12+19 / SUB -12]; corners 7 / 6 / 2 kHz at 44.1 kHz; 3 / 2.2 / 2 kHz at")
    w(" * 22.05 kHz, the shimmer's run twice there (aliases above fs / 2r); SUB's once (no alias: kept clean) */")
    w("static const int16_t sp_shbq[2][3][5] = {")
    for fs, corners in ((44100, (7000, 6000, 2000)), (22050, (3000, 2200, 2000))):
        w("    {")
        for fc in corners:
            wq = 2 * math.pi * fc / fs
            al, c = math.sin(wq) / (2 * 0.7071), math.cos(wq)
            a0 = 1 + al
            b0, a1, a2 = (1 - c) / 2 / a0, -2 * c / a0, (1 - al) / a0
            q = [round(v * 16384) for v in (b0, 2 * b0, b0, a1, a2)]
            q[1] = q[3] + q[4] + 16384 - q[0] - q[2]                  # unity at DC exactly
            w("        { " + ", ".join(map(str, q)) + " },")
        w("    },")
    w("};\n")
    w("#endif")
    open(OUT, "w").write("\n".join(L) + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}: half-band {hb} (sum {2 * sum(hb) + 16384} / 32768)")


if __name__ == "__main__":
    main()
