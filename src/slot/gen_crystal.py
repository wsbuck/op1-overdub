#!/usr/bin/env python3
"""Generate crystal.h for the modal engine's screen (ui.c): krystal's crystal habits and jitter.

  python3 src/slot/gen_crystal.py > src/slot/crystal.h

Port of krystal/firmware/engines/modal/modal_visual.cpp: kHabits[8] = {sides, half-height, termination,
ring radius, girdle radius} (fractions of the size, here Q12) and kJit (Lcg(977).uniform() - 0.5, Q15).
"""
HABITS = [
    (6, 0.52, 0.42, 0.34, 0.34),  # String
    (4, 0.50, 0.34, 0.46, 0.46),  # Bar
    (6, 0.34, 0.42, 0.52, 0.72),  # Bell
    (8, 0.14, 0.26, 0.78, 1.00),  # Gong
    (6, 0.20, 0.40, 0.62, 0.95),  # Membrane
    (5, 0.34, 0.42, 0.56, 0.82),  # Glass
    (4, 0.12, 0.20, 0.82, 1.00),  # Plate
    (7, 0.30, 0.52, 0.50, 0.86),  # Impossible
]


def main():
    s, jit = 977, []
    for _ in range(64):
        s = (s * 1664525 + 1013904223) & 0xFFFFFFFF
        jit.append(round((s / 4294967296.0 - 0.5) * 32768))
    print("/* Generated by gen_crystal.py; do not edit. */")
    print("static const int16_t crystal_habit[8][5] = {")
    for h in HABITS:
        print("    {" + f"{h[0]}, " + ", ".join(str(round(v * 4096)) for v in h[1:]) + "},")
    print("};")
    print("static const int16_t crystal_jit[64] = {")
    for i in range(0, 64, 16):
        print("    " + " ".join(f"{v}," for v in jit[i:i + 16]))
    print("};")


if __name__ == "__main__":
    main()
