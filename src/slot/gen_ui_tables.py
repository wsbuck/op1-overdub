#!/usr/bin/env python3
"""Generate ui_tables.h for the screens (ui.c).

  python3 src/slot/gen_ui_tables.py > src/slot/ui_tables.h

va filter curve: low-pass magnitude in dB, -10 log10((1 - w^2)^2 + (w / Q)^2) with w = 2^r, for r = -2 .. +2
octaves around the cutoff in 0.25-octave steps (17 points) and 9 resonance rows. va.c's resonance knob gives
k = 2 - 1.9 res, Q = 1 / k; va_q_row_min[i] is the smallest knob value that selects row i (nearest Q).
Values are dB * 16 (int16).
"""
import math

QS = [0.5, 0.7, 1.0, 1.5, 2.0, 3.0, 5.0, 7.0, 10.0]


def main():
    print("/* Generated by gen_ui_tables.py; do not edit. */")
    print("#ifndef UI_TABLES_H\n#define UI_TABLES_H\n#include <stdint.h>\n")
    print(f"#define VA_LP_ROWS {len(QS)}\n#define VA_LP_POINTS 17")
    print("static const int16_t va_lp_db16[VA_LP_ROWS][VA_LP_POINTS] = {")
    for q in QS:
        row = []
        for i in range(17):
            w = 2 ** ((i - 8) / 4)
            db = -10 * math.log10((1 - w * w) ** 2 + (w / q) ** 2)
            row.append(round(db * 16))
        print("    {" + ", ".join(map(str, row)) + "},")
    print("};")
    # knob threshold per row: midpoint (in log Q) between neighbouring rows, knob = (2 - 1/Q) / 1.9 * 32767
    th = [0]
    for a, b in zip(QS, QS[1:]):
        qm = math.sqrt(a * b)
        th.append(max(0, min(32767, round((2 - 1 / qm) / 1.9 * 32767))))
    print("static const int16_t va_q_row_min[VA_LP_ROWS] = {" + ", ".join(map(str, th)) + "};")
    print("\n#endif")


if __name__ == "__main__":
    main()
