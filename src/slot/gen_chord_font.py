#!/usr/bin/env python3
"""Generate chord_font.h for CHORD v2 (ui_chord2.h): gen_font.py's stroke font plus chord symbols, with a
per-glyph advance so short chord names fit on a key.

  python3 src/slot/gen_chord_font.py > src/slot/chord_font.h

Extra glyphs (ASCII stand-ins): '#' sharp, '&' flat (narrow b), '^' major-7 triangle, '*' diminished circle,
'$' half-diminished (circle with slash), '(' ')' brackets, '<' '>' arrows, '!' a small dot,
'[' ']' '\\' the LIFT / DROP / SPLIT key icons, '{' '}' arrows up / down (STRUM), '|' a centre mark, '~' a lower-case m (minor intervals).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_font import G as BASE, segments  # noqa: E402

G = dict(BASE)
G.update({
    "#": ["11 15", "31 35", "02 42", "04 44"],
    "&": ["00 06 26 23 03"],                    # flat: stem and a small bowl, 3 wide
    "^": ["06 22 46 06"],                       # major 7 triangle, x-height
    "*": ["02 22 24 04 02"],                    # diminished: small ring, top
    "$": ["02 22 24 04 02", "05 31"],           # half-diminished: ring with a slash
    "(": ["20 01 05 26"],
    ")": ["00 21 25 06"],
    "<": ["30 03 36"],
    ">": ["00 33 06"],
    "!": ["13 23"],
    "[": ["21 25", "12 21 32", "06 46"],        # LIFT key icon: arrow up on a bar
    "]": ["00 40", "21 25", "14 25 34"],        # DROP key icon: arrow down from a bar
    "\\": ["00 34", "40 04", "04 15 06 04", "44 35 46 44"],   # SPLIT key icon: scissors
    "{": ["20 26", "02 20 42"],                 # arrow up (STRUM up: low to high)
    "}": ["20 26", "04 26 44"],                 # arrow down
    "|": ["20 26"],                             # centre mark
    "~": ["06 02 42 46", "22 26"],              # a lower-case m (minor intervals: m3, m10), x-height
})
NARROW = {"~": 6, "{": 5, "}": 5, "|": 4, "&": 4, "^": 6, "*": 4, "$": 5, "(": 4, ")": 4, "1": 5, "I": 5, ".": 4, ":": 4, "!": 4, " ": 4, "-": 6}


def main():
    data, offs, adv = [], [], []
    for c in range(0x20, 0x7F):  # ' '..'~' (lower case is drawn upper case: never looked up)
        offs.append(len(data))
        for a, b in segments(G.get(chr(c), [])):
            data += [a, b]
        data.append(0xFF)
        adv.append(NARROW.get(chr(c), 6))
    print("/* Generated by src/slot/gen_chord_font.py; do not edit. gen_font.py's glyphs plus chord symbols. */")
    print("#define CFONT_FIRST 0x20")
    print("#define CFONT_LAST 0x7E")
    print(f"static const uint16_t cfont_off[{len(offs)}] = {{")
    for i in range(0, len(offs), 12):
        print("    " + " ".join(f"{o}," for o in offs[i:i + 12]))
    print("};")
    print(f"static const uint8_t cfont_adv[{len(adv)}] = {{")
    for i in range(0, len(adv), 16):
        print("    " + " ".join(f"{o}," for o in adv[i:i + 16]))
    print("};")
    print(f"static const uint8_t cfont_seg[{len(data)}] = {{")
    for i in range(0, len(data), 16):
        print("    " + " ".join(f"0x{b:02x}," for b in data[i:i + 16]))
    print("};")


if __name__ == "__main__":
    main()
